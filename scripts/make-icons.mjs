#!/usr/bin/env node
// Generates favicons, app icons, a web manifest and a link-preview image for every tool, and wires them into
// each tool's index.html. Run from shared-kit with the tool repos checked out next to it:
//   node scripts/make-icons.mjs            (uses https://scda-<id>.pages.dev for absolute URLs)
//   SITE_TEMPLATE='https://{sub}.example.org' node scripts/make-icons.mjs   (after a custom domain)
// Needs rsvg-convert (librsvg) on PATH.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOL_ICONS, iconSvg, BADGE_BG } from '../packages/ui/src/icons-data.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const REPOS = { hub: 'hub', cargo: 'cargo-manifest', fleet: 'fleet-planner', ops: 'ops-planner', trade: 'trade-data', market: 'resource-exchange' };
const SUB = { hub: '', cargo: 'cargo', fleet: 'fleet', ops: 'ops', trade: 'trade', market: 'market' };
const TAGLINE = {
  hub: 'Org management, recruitment and a launcher for every tool',
  cargo: 'Cargo grids, inventory, refinery jobs and org stockpiles',
  fleet: 'Your hangar and your org fleet, crew positions and roles',
  ops: 'Plan ops, fill crew seats, Discord reminders and payouts',
  trade: 'Hourly commodity prices, trade routes and price alerts',
  market: 'Buy, sell and contract with other players for aUEC',
};
const template = process.env.SITE_TEMPLATE || 'https://scda-{id}.pages.dev';
const siteUrl = (id) => template.replaceAll('{id}', id).replaceAll('{sub}', SUB[id]).replace(/\/$/, '') + '/';

const tmp = mkdtempSync(join(tmpdir(), 'icons-'));
function png(svg, size, out) {
  const src = join(tmp, `${Math.random().toString(36).slice(2)}.svg`);
  writeFileSync(src, svg);
  execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), src, '-o', out]);
}
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

function ogSvg(id) {
  const t = TOOL_ICONS[id];
  const others = Object.keys(TOOL_ICONS).filter((k) => k !== id);
  const badge = (k, x, y, s) => `<g transform="translate(${x} ${y}) scale(${s / 64})">${iconSvg(k).replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    <radialGradient id="glow" cx="0.22" cy="0.45" r="0.6"><stop offset="0" stop-color="${t.color}" stop-opacity=".22"/><stop offset="1" stop-color="${t.color}" stop-opacity="0"/></radialGradient>
    <pattern id="grid" width="40" height="40" patternUnits="userSpaceOnUse"><path d="M40 0H0V40" fill="none" stroke="#1f2f42" stroke-width="1" opacity=".5"/></pattern>
  </defs>
  <rect width="1200" height="630" fill="#080d13"/>
  <rect width="1200" height="630" fill="url(#grid)"/>
  <rect width="1200" height="630" fill="url(#glow)"/>
  ${badge(id, 90, 165, 260)}
  <text x="410" y="250" font-family="Inter" font-weight="700" font-size="30" letter-spacing="6" fill="#7f93a8">SC ORG TOOLS</text>
  <text x="410" y="330" font-family="Inter" font-weight="700" font-size="76" fill="#d9e4ee">${esc(t.label)}</text>
  <text x="410" y="390" font-family="Inter" font-weight="500" font-size="26" fill="${t.color}">${esc(TAGLINE[id])}</text>
  ${others.map((k, i) => badge(k, 410 + i * 70, 450, 52)).join('\n  ')}
  <text x="1110" y="590" text-anchor="end" font-family="Inter" font-size="20" fill="#7f93a8">Free, fan-made tools for Star Citizen orgs</text>
</svg>`;
}

const HEAD_START = '<!-- icons:start (generated by shared-kit/scripts/make-icons.mjs) -->';
const HEAD_END = '<!-- icons:end -->';

for (const [id, repo] of Object.entries(REPOS)) {
  const dir = join(root, repo);
  if (!existsSync(join(dir, 'index.html'))) {
    console.warn(`skip ${repo}: not checked out`);
    continue;
  }
  const pub = join(dir, 'public');
  mkdirSync(pub, { recursive: true });
  const t = TOOL_ICONS[id];
  writeFileSync(join(pub, 'favicon.svg'), iconSvg(id));
  png(iconSvg(id), 32, join(pub, 'favicon-32.png'));
  png(iconSvg(id, { rounded: false, padding: 7 }), 180, join(pub, 'apple-touch-icon.png'));
  png(iconSvg(id, { rounded: false, padding: 7 }), 192, join(pub, 'icon-192.png'));
  png(iconSvg(id, { rounded: false, padding: 9 }), 512, join(pub, 'icon-512.png'));
  const og = ogSvg(id);
  const ogSrc = join(tmp, `og-${id}.svg`);
  writeFileSync(ogSrc, og);
  execFileSync('rsvg-convert', ['-w', '1200', '-h', '630', ogSrc, '-o', join(pub, 'og-image.png')]);
  const name = id === 'hub' ? 'SC Org Tools' : `${t.label} · SC Org Tools`;
  writeFileSync(join(pub, 'site.webmanifest'), JSON.stringify({
    name, short_name: id === 'hub' ? 'Org Tools' : t.label.split(' ')[0], start_url: '/', scope: '/', display: 'standalone',
    background_color: '#080d13', theme_color: BADGE_BG,
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
      { src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' },
    ],
  }, null, 2) + '\n');

  const url = siteUrl(id);
  const head = [
    HEAD_START,
    '<link rel="icon" href="/favicon.svg" type="image/svg+xml" />',
    '<link rel="icon" href="/favicon-32.png" sizes="32x32" type="image/png" />',
    '<link rel="apple-touch-icon" href="/apple-touch-icon.png" />',
    '<link rel="manifest" href="/site.webmanifest" />',
    `<meta name="theme-color" content="${BADGE_BG}" />`,
    `<meta name="description" content="${esc(TAGLINE[id])}. Free, fan-made tools for Star Citizen orgs." />`,
    `<meta property="og:title" content="${esc(name)}" />`,
    `<meta property="og:description" content="${esc(TAGLINE[id])}." />`,
    '<meta property="og:type" content="website" />',
    `<meta property="og:url" content="${url}" />`,
    `<meta property="og:image" content="${url}og-image.png" />`,
    '<meta property="og:image:width" content="1200" />',
    '<meta property="og:image:height" content="630" />',
    '<meta name="twitter:card" content="summary_large_image" />',
    HEAD_END,
  ].map((l) => `    ${l}`).join('\n');
  let html = readFileSync(join(dir, 'index.html'), 'utf8');
  const re = new RegExp(`\\s*${HEAD_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${HEAD_END}`);
  html = re.test(html) ? html.replace(re, '\n' + head) : html.replace(/(<\/title>)/, '$1\n' + head);
  writeFileSync(join(dir, 'index.html'), html);
  console.log(`${repo}: icons, manifest, og-image, index.html`);
}
