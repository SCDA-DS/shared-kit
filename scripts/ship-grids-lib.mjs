// Pure helpers: Star Citizen Wiki API vehicles → cargo-grid presets (SCU cells; 1 SCU = 1.25 m cube).

export const WIKI_API = 'https://api.star-citizen.wiki/api/v2/vehicles';
export const SIZES = [1, 2, 4, 8, 16, 24, 32];
const SKIP = /\bDisplay\b/i;

const cells = (m) => {
  const n = Number(m) / 1.25;
  return Number.isInteger(n) && n > 0 ? n : Math.round(n) || null;
};

/** A grid's largest box. The API reports 1 SCU for some big grids where no limit is set, so 1 only counts on small grids. */
export function maxBox(raw, w, l, h) {
  const m = Number(raw);
  if (!SIZES.includes(m)) return undefined;
  if (m === 1 && w * l * h > 8) return undefined;
  return m;
}

export function convertGrid(g) {
  const w = cells(g.width), l = cells(g.length), h = cells(g.height);
  if (!w || !l || !h) return null;
  return { w, l, h, max: maxBox(g.max_scu_box, w, l, h), external: !!g.external };
}

/** Name grids "Hold", "Hold 1…", "External 1…". */
export function nameGrids(grids) {
  const internal = grids.filter((g) => !g.external);
  const external = grids.filter((g) => g.external);
  const label = (list, base) => list.map((g, i) => ({ ...g, name: list.length === 1 ? base : `${base} ${i + 1}` }));
  return [...label(internal, 'Hold'), ...label(external, 'External')];
}

/** Vehicles with cargo grids → presets, one per in-game name, sorted. */
export function toPresets(vehicles) {
  const seen = new Set();
  const out = [];
  for (const v of vehicles) {
    const model = String(v.game_name || v.name || '').replace(/\s+/g, ' ').trim();
    if (!model || SKIP.test(model) || seen.has(model)) continue;
    const grids = (v.cargo_grids ?? []).map(convertGrid).filter(Boolean);
    if (!grids.length) continue;
    seen.add(model);
    out.push({
      model,
      maker: v.manufacturer?.name ?? null,
      scu: grids.reduce((t, g) => t + g.w * g.l * g.h, 0),
      grids: nameGrids(grids).map(({ name, w, l, h, max }) => (max ? { name, w, l, h, max } : { name, w, l, h })),
    });
  }
  return out.sort((a, b) => a.model.localeCompare(b.model));
}

export function renderModule(presets, { fetchedAt }) {
  return `// GENERATED by scripts/update-ship-grids.mjs from the Star Citizen Wiki API (${WIKI_API}).
// Do not edit by hand — run the "Update ship cargo grids" workflow (or the script) to refresh.
// Fetched ${fetchedAt}. ${presets.length} ships with cargo grids.
import type { CargoGrid } from './cargo';

export interface GeneratedShip {
  model: string;
  maker: string | null;
  scu: number;
  grids: CargoGrid[];
}

export const SHIP_GRIDS_FETCHED_AT = ${JSON.stringify(fetchedAt)};

export const GENERATED_SHIPS: GeneratedShip[] = ${JSON.stringify(presets, null, 1)
    .replace(/\n\s*/g, ' ')
    .replace(/\{ "model"/g, '\n  { "model"')
    .replace(/\] \]$/, ']\n]')} as GeneratedShip[];
`;
}
